// Basic of For loop
 for(let i:number=1; i<=10; i++){
    console.log(i)

 }

 // reverse printing
 for(let j=10; j>=1; j--){
    console.log(j)
 }

 // global variable
 let z:number;
 for (z=1; z<=5; z++){
    console.log(z)
 }

 console.log(z)

 // break
  for(let m=10; m>=1; m--){
    if(m==6){
        break;
    }
    console.log(m)
 }

 // continue
  for(let n=10; n>=1; n--){
    if(n==6){
        continue;
    }
    console.log(n)
 }
